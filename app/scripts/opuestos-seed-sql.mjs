// Generates supabase/seed/opuestos.sql from src/content/opuestos.json (the single
// source of truth for El Rayo Modificador). Run from app/, after migration 0004:
//   node scripts/opuestos-seed-sql.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const SRC = "src/content/opuestos.json";
const OUT = "supabase/seed/opuestos.sql";

const { words, levels } = JSON.parse(readFileSync(SRC, "utf8"));
const q = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const num = (n) => {
  if (typeof n !== "number" || !Number.isFinite(n)) throw new Error(`not a number: ${n}`);
  return String(n);
};
const textArray = (xs) => (xs.length ? `array[${xs.map(q).join(", ")}]::text[]` : "'{}'::text[]");

const ids = new Set(words.map((w) => w.id));
for (const w of words) if (!ids.has(w.antonym_id)) throw new Error(`${w.id}: antonym ${w.antonym_id} missing`);

const wordCols = ["word", "antonym_id", "engine_target", "value_modifier", "shader_trigger", "translation", "category", "sort"];
const levelCols = ["sort", "title_es", "title_en", "clue_es", "clue_en", "words", "layout"];

const lines = [
  `-- GENERATED by scripts/opuestos-seed-sql.mjs from ${SRC}. Do not edit by hand.`,
  "-- Idempotent: upserts every word and level, and deletes rows that left the JSON.",
  "begin;",
  // antonym_id is a self-reference (deferrable initially deferred): pairs can be
  // inserted in any order and are checked at commit.
  "set constraints all deferred;",
  "",
  `delete from todo.opuestos_levels where id not in (${levels.map((l) => q(l.id)).join(", ")});`,
  // Park existing sorts out of the way so reordered levels can't trip unique(sort) mid-upsert.
  "update todo.opuestos_levels set sort = -sort - 1000;",
  `delete from todo.opuestos_words where id not in (${words.map((w) => q(w.id)).join(", ")});`,
  "",
];

for (const w of words) {
  lines.push(
    `insert into todo.opuestos_words (id, ${wordCols.join(", ")}) values (${[
      q(w.id),
      q(w.word),
      q(w.antonym_id),
      q(w.engine_target),
      num(w.value_modifier),
      q(w.shader_trigger),
      q(w.translation),
      q(w.category),
      num(w.sort),
    ].join(", ")})`,
    `  on conflict (id) do update set ${wordCols.map((c) => `${c} = excluded.${c}`).join(", ")};`,
  );
}
lines.push("");

for (const l of levels) {
  lines.push(
    `insert into todo.opuestos_levels (id, ${levelCols.join(", ")}) values (${[
      q(l.id),
      num(l.sort),
      q(l.title_es),
      q(l.title_en),
      q(l.clue_es),
      q(l.clue_en),
      textArray(l.words),
      `${q(JSON.stringify(l.layout))}::jsonb`,
    ].join(", ")})`,
    `  on conflict (id) do update set ${levelCols.map((c) => `${c} = excluded.${c}`).join(", ")};`,
  );
}

lines.push("", "commit;", "");
mkdirSync(new URL("../supabase/seed/", import.meta.url), { recursive: true });
writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${OUT} (${words.length} words, ${levels.length} levels)`);

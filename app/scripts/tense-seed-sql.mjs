// Generates supabase/seed/tense.sql from src/content/tense.json (the single source
// of truth for The Memory Diorama's learning content). Run from app/:
//   node scripts/tense-seed-sql.mjs
// Then apply the file to the database (after migrations/0001_todo_schema.sql).
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "src/content/tense.json";
const OUT = "supabase/seed/tense.sql";

const { rooms } = JSON.parse(readFileSync(SRC, "utf8"));
const q = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);

const puzzleCols = [
  "room_id",
  "order_index",
  "scene_object",
  "sentence_pre",
  "sentence_post",
  "verb_base",
  "options",
  "rule_feedback",
  "translation",
  "anim_trigger",
];

const lines = [
  `-- GENERATED by scripts/tense-seed-sql.mjs from ${SRC}. Do not edit by hand.`,
  "begin;",
  "",
  // Content is replaced wholesale: rooms or puzzles removed from the JSON go too,
  // and moved puzzles can't trip the (room_id, order_index) / (room_id, scene_object)
  // unique constraints mid-upsert. Puzzle ids are stable, so game_attempts.item_ref
  // and review cards keep resolving.
  `delete from todo.tense_puzzles where id not in (${rooms.flatMap((r) => r.puzzles.map((p) => q(p.id))).join(", ")});`,
  `delete from todo.tense_rooms where id not in (${rooms.map((r) => q(r.id)).join(", ")});`,
  "update todo.tense_puzzles set order_index = -order_index - 1000, scene_object = scene_object || '#' || id;",
  "update todo.tense_rooms set order_index = -order_index - 1000;",
  "",
];

for (const r of rooms) {
  lines.push(
    `insert into todo.tense_rooms (id, order_index, title, subtitle, focus) values (${q(r.id)}, ${r.order_index}, ${q(r.title)}, ${q(r.subtitle)}, ${q(r.focus)})`,
    `  on conflict (id) do update set order_index = excluded.order_index, title = excluded.title, subtitle = excluded.subtitle, focus = excluded.focus;`,
  );
}
lines.push("");

for (const r of rooms) {
  for (const p of r.puzzles) {
    lines.push(
      `insert into todo.tense_puzzles (id, ${puzzleCols.join(", ")}) values (${[
        q(p.id),
        q(r.id),
        p.order_index,
        q(p.scene_object),
        q(p.sentence_pre),
        q(p.sentence_post),
        q(p.verb_base),
        `${q(JSON.stringify(p.options))}::jsonb`,
        q(p.rule_feedback),
        q(p.translation),
        q(p.anim_trigger),
      ].join(", ")})`,
      `  on conflict (id) do update set ${puzzleCols.map((c) => `${c} = excluded.${c}`).join(", ")};`,
    );
  }
}

lines.push("", "commit;", "");
writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${OUT} (${rooms.length} rooms, ${rooms.reduce((n, r) => n + r.puzzles.length, 0)} puzzles)`);

// Generates supabase/seed/donde.sql from src/content/donde.json (the bundled fallback curriculum).
// Upserts todo.donde_pages / todo.donde_tasks and deletes tasks/pages no longer in the JSON.
// Usage (from app/): node scripts/donde-seed-sql.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const book = JSON.parse(readFileSync(new URL("../src/content/donde.json", import.meta.url), "utf8"));

const lit = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const json = (v) => (v === null || v === undefined ? "null" : `${lit(JSON.stringify(v))}::jsonb`);
const arr = (v) => `array[${v.map(lit).join(", ")}]::text[]`;

const MECHANICS = ["drag", "flap", "pick", "pin", "build"];
const LAYERS = ["pop_up_apartment", "polaroid_plaza", "botanico_map"];

const pageIds = book.pages.map((p) => p.page_id);
const taskIds = book.pages.flatMap((p) => p.tasks.map((t) => t.id));

const lines = [
  "-- Generated by scripts/donde-seed-sql.mjs from src/content/donde.json. Do not edit by hand.",
  "begin;",
  // Free up (page_id, sort) and page sort so reordering can't collide with the unique constraints.
  `delete from todo.donde_tasks where id not in (${taskIds.map(lit).join(", ")});`,
  `delete from todo.donde_pages where page_id not in (${pageIds.map(lit).join(", ")});`,
  "update todo.donde_tasks set sort = sort + 1000;",
  "update todo.donde_pages set sort = sort + 1000;",
];

book.pages.forEach((page, p) => {
  if (!LAYERS.includes(page.visual_layer)) throw new Error(`${page.page_id}: visual_layer ${page.visual_layer} violates the DB check`);
  lines.push(
    `insert into todo.donde_pages (page_id, sort, title_es, title_en, visual_layer) values (${lit(page.page_id)}, ${p + 1}, ${lit(page.title_es)}, ${lit(page.title_en)}, ${lit(page.visual_layer)})` +
      " on conflict (page_id) do update set sort = excluded.sort, title_es = excluded.title_es, title_en = excluded.title_en, visual_layer = excluded.visual_layer;",
  );
  page.tasks.forEach((t, i) => {
    if (!MECHANICS.includes(t.mechanic)) throw new Error(`${t.id}: mechanic ${t.mechanic} violates the DB check`);
    lines.push(
      "insert into todo.donde_tasks (id, page_id, sort, mechanic, prompt_text, prompt_en, draggable_id, target_zone, error_note, success_note, zone_notes, build, tags, level) values (" +
        [
          lit(t.id),
          lit(page.page_id),
          i + 1,
          lit(t.mechanic),
          lit(t.prompt_text),
          lit(t.prompt_en),
          lit(t.draggable_id),
          lit(t.target_zone),
          lit(t.error_note),
          lit(t.success_note),
          json(t.zone_notes ?? {}),
          json(t.build),
          arr(t.tags ?? []),
          lit(t.level),
        ].join(", ") +
        ") on conflict (id) do update set page_id = excluded.page_id, sort = excluded.sort, mechanic = excluded.mechanic, prompt_text = excluded.prompt_text," +
        " prompt_en = excluded.prompt_en, draggable_id = excluded.draggable_id, target_zone = excluded.target_zone, error_note = excluded.error_note," +
        " success_note = excluded.success_note, zone_notes = excluded.zone_notes, build = excluded.build, tags = excluded.tags, level = excluded.level;",
    );
  });
});

lines.push("commit;", "");
mkdirSync(new URL("../supabase/seed/", import.meta.url), { recursive: true });
writeFileSync(new URL("../supabase/seed/donde.sql", import.meta.url), lines.join("\n"));
console.log(`wrote supabase/seed/donde.sql (${book.pages.length} pages, ${taskIds.length} tasks)`);

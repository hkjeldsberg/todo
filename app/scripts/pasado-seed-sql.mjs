// Generates supabase/seed/pasado.sql from src/content/pasado.json (the single source of
// truth for El Candado del Tiempo). Run from app/, after migration 0008 and seed/verbs.sql:
//   npm run pasado:seed
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const SRC = "src/content/pasado.json";
const OUT = "supabase/seed/pasado.sql";

const { drills } = JSON.parse(readFileSync(SRC, "utf8"));
const q = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);

const cols = ["infinitive", "person", "sentence_template", "correct_tense", "trigger_word", "english_translation"];

const lines = [
  `-- GENERATED by scripts/pasado-seed-sql.mjs from ${SRC}. Do not edit by hand.`,
  // Upsert only: drills added straight in the DB (no redeploy) must survive a re-seed.
  "-- Idempotent: upserts every drill in the JSON. Rows not in the JSON are left alone.",
  "begin;",
  "",
];

for (const d of drills) {
  lines.push(
    `insert into todo.past_drills (id, ${cols.join(", ")}) values (${[d.id, ...cols.map((c) => d[c])].map(q).join(", ")})`,
    `  on conflict (id) do update set ${cols.map((c) => `${c} = excluded.${c}`).join(", ")};`,
  );
}

lines.push("", "commit;", "");
mkdirSync(new URL("../supabase/seed/", import.meta.url), { recursive: true });
writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${OUT} (${drills.length} drills)`);

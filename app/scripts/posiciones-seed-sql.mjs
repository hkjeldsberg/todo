// Generates supabase/seed/posiciones.sql from src/content/posiciones.json (the single
// source of truth for El Laberinto del Gnomo). Run from app/, after migration 0007:
//   node scripts/posiciones-seed-sql.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const SRC = "src/content/posiciones.json";
const OUT = "supabase/seed/posiciones.sql";

const { expressions, scenes } = JSON.parse(readFileSync(SRC, "utf8"));
const q = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const num = (n) => {
  if (typeof n !== "number" || !Number.isFinite(n)) throw new Error(`not a number: ${n}`);
  return String(n);
};
const bool = (b) => (b ? "true" : "false");
const textArray = (xs) => (xs.length ? `array[${xs.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const jsonb = (v) => `${q(JSON.stringify(v))}::jsonb`;

// Light integrity checks (the zod schema in the app is the real gate).
const ids = new Set(expressions.map((e) => e.id));
if (ids.size !== expressions.length) throw new Error("duplicate expression id");
for (const s of scenes) {
  const objs = new Set(s.objects.map((o) => o.id));
  for (const f of s.facts) {
    if (!ids.has(f.expression)) throw new Error(`${s.id}: unknown expression ${f.expression}`);
    if (!s.targets.includes(f.target)) throw new Error(`${s.id}: unknown spot ${f.target}`);
    for (const r of f.refs ?? []) if (!objs.has(r)) throw new Error(`${s.id}: unknown object ${r}`);
  }
}

const exprCols = ["es", "en", "level", "category", "needs_reference", "ref_count", "region", "notes", "sort"];
const sceneCols = ["sort", "title_es", "title_en", "visual_layer", "objects", "facts", "targets"];

const lines = [
  `-- GENERATED by scripts/posiciones-seed-sql.mjs from ${SRC}. Do not edit by hand.`,
  "-- Idempotent: upserts every expression and scene, and deletes rows that left the JSON.",
  "begin;",
  "",
  `delete from todo.posiciones_expressions where id not in (${expressions.map((e) => q(e.id)).join(", ")});`,
  `delete from todo.posiciones_scenes where id not in (${scenes.map((s) => q(s.id)).join(", ")});`,
  // Park existing sorts out of the way so reordered scenes can't trip unique(sort) mid-upsert.
  "update todo.posiciones_scenes set sort = -sort - 1000;",
  "",
];

for (const e of expressions) {
  lines.push(
    `insert into todo.posiciones_expressions (id, ${exprCols.join(", ")}) values (${[
      q(e.id),
      q(e.es),
      q(e.en),
      q(e.level),
      q(e.category),
      bool(e.needs_reference),
      num(e.ref_count),
      q(e.region),
      q(e.notes),
      num(e.sort),
    ].join(", ")})`,
    `  on conflict (id) do update set ${exprCols.map((c) => `${c} = excluded.${c}`).join(", ")};`,
  );
}
lines.push("");

for (const s of scenes) {
  lines.push(
    `insert into todo.posiciones_scenes (id, ${sceneCols.join(", ")}) values (${[
      q(s.id),
      num(s.sort),
      q(s.title_es),
      q(s.title_en),
      q(s.visual_layer),
      jsonb(s.objects),
      jsonb(s.facts),
      textArray(s.targets),
    ].join(", ")})`,
    `  on conflict (id) do update set ${sceneCols.map((c) => `${c} = excluded.${c}`).join(", ")};`,
  );
}

lines.push("", "commit;", "");
mkdirSync(new URL("../supabase/seed/", import.meta.url), { recursive: true });
writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${OUT} (${expressions.length} expressions, ${scenes.length} scenes)`);

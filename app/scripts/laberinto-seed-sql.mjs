// Generates supabase/seed/laberinto.sql from src/content/laberinto.json (single source of truth).
//   node scripts/laberinto-seed-sql.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const src = new URL("../src/content/laberinto.json", import.meta.url);
const out = new URL("../supabase/seed/laberinto.sql", import.meta.url);
const nodes = JSON.parse(readFileSync(src, "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);

const rows = nodes.map(
  (n) =>
    `  (${q(n.node_id)}, ${q(n.island_zone)}, ${n.seq}, ${q(n.ambient_prompt)}, ${q(JSON.stringify(n.doors))}::jsonb, ${q(n.feedback_imperfect)}, ${q(n.next_node_id)})`,
);

const sql = `-- Generated by scripts/laberinto-seed-sql.mjs from src/content/laberinto.json — do not edit by hand.
begin;
set constraints all deferred;
insert into todo.laberinto_nodes (node_id, island_zone, seq, ambient_prompt, doors, feedback_imperfect, next_node_id) values
${rows.join(",\n")}
on conflict (node_id) do update set
  island_zone = excluded.island_zone,
  seq = excluded.seq,
  ambient_prompt = excluded.ambient_prompt,
  doors = excluded.doors,
  feedback_imperfect = excluded.feedback_imperfect,
  next_node_id = excluded.next_node_id;
commit;
`;
mkdirSync(new URL(".", out), { recursive: true });
writeFileSync(out, sql);
console.log(`Wrote ${nodes.length} nodes to supabase/seed/laberinto.sql`);

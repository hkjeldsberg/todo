// Generates supabase/seed/probador.sql from src/content/probador.json (the single source of
// truth for El Probador). Run from app/, after migration 0009:
//   npm run probador:seed
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const SRC = "src/content/probador.json";
const OUT = "supabase/seed/probador.sql";

const { outfits, prompts } = JSON.parse(readFileSync(SRC, "utf8"));
const q = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const sentence = (p) => `${p.answer_parts.pronoun} ${p.answer_parts.verb} ${p.answer_parts.complement}.`;

function upsert(table, row) {
  const cols = Object.keys(row);
  const rest = cols.filter((c) => c !== "id");
  return [
    `insert into todo.${table} (${cols.join(", ")}) values (${Object.values(row).join(", ")})`,
    `  on conflict (id) do update set ${rest.map((c) => `${c} = excluded.${c}`).join(", ")};`,
  ];
}

const lines = [
  `-- GENERATED by scripts/probador-seed-sql.mjs from ${SRC}. Do not edit by hand.`,
  "-- Idempotent: upserts every outfit and prompt in the JSON. Rows not in the JSON are left alone.",
  "begin;",
  "",
];
for (const o of outfits) {
  lines.push(
    ...upsert("probador_outfits", {
      id: q(o.id),
      avatar: j(o.avatar),
      layers: j(o.layers),
      description: q(o.description),
      intended_flaw: q(o.intended_flaw),
    }),
  );
}
lines.push("");
for (const p of prompts) {
  lines.push(
    ...upsert("probador_prompts", {
      id: q(p.id),
      outfit_id: q(p.outfit_id),
      target_verb: q(p.target_verb),
      question_text: q(p.question_text),
      question_fill: q(p.question_fill),
      correct_answer_syntax: q(sentence(p)),
      answer_parts: j(p.answer_parts),
      distractor_options: j(p.distractor_options),
      english_translation: q(p.english_translation),
    }),
  );
}
lines.push("", "commit;", "");
mkdirSync(new URL("../supabase/seed/", import.meta.url), { recursive: true });
writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${OUT} (${outfits.length} outfits, ${prompts.length} prompts)`);

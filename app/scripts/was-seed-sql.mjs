// Generates supabase/seed/was.sql from src/content/was.json (the single source of
// truth for El Cómic Dinámico). Run from app/, after migration 0005:
//   npm run was:seed
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const SRC = "src/content/was.json";
const OUT = "supabase/seed/was.sql";

const { panels } = JSON.parse(readFileSync(SRC, "utf8"));
const q = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const num = (n) => {
  if (!Number.isInteger(n)) throw new Error(`not an integer: ${n}`);
  return String(n);
};

const cols = [
  "page_id",
  "panel_order",
  "panel_type",
  "sentence_pre",
  "sentence_post",
  "correct_verb",
  "rule_feedback",
  "asset_sketch",
  "asset_color",
];

const lines = [
  `-- GENERATED by scripts/was-seed-sql.mjs from ${SRC}. Do not edit by hand.`,
  // Upsert only: pages added straight in the DB (no redeploy) must survive a re-seed.
  "-- Idempotent: upserts every panel in the JSON. Rows not in the JSON are left alone.",
  "begin;",
  "",
  // Park the JSON's own rows out of the way so reordered panels can't trip unique(page_id, panel_order) mid-upsert.
  `update todo.was_panels set panel_order = panel_order + 1000 where id in (${panels.map((p) => q(p.id)).join(", ")});`,
  "",
];

for (const p of panels) {
  lines.push(
    `insert into todo.was_panels (id, ${cols.join(", ")}) values (${[
      q(p.id),
      q(p.page_id),
      num(p.panel_order),
      q(p.panel_type),
      q(p.sentence_pre),
      q(p.sentence_post),
      q(p.correct_verb),
      q(p.rule_feedback),
      q(p.asset_sketch),
      q(p.asset_color),
    ].join(", ")})`,
    `  on conflict (id) do update set ${cols.map((c) => `${c} = excluded.${c}`).join(", ")};`,
  );
}

lines.push("", "commit;", "");
mkdirSync(new URL("../supabase/seed/", import.meta.url), { recursive: true });
writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${OUT} (${panels.length} panels)`);
